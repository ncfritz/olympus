export class Revocation {
  @ApiProperty({
    ...REVOCATION_REASON_ENUM,
    required: true,
    description: "Why it was revoked",
  })
  reason: RevocationReasonName;

  @ApiTimestamp({
    required: true,
    description: "An ISO-8601 formatted string: when it was revoked",
  })
  revokedAt: Moment;

  @ApiProperty({ type: String, required: true, description: "Who revoked it" })
  principal: string;

  @ApiProperty({
    type: String,
    required: false,
    description: "What they said about it",
  })
  comment?: string;
}

/** A certificate Harpocrates issued (or imported). */
export class Certificate {
  @ApiProperty({ type: String, required: true, description: "Its ID" })
  id: string;

  @ApiProperty({
    type: String,
    required: true,
    description: "The CA that issued it",
  })
  issuerId: string;

  @ApiProperty({
    type: String,
    required: false,
    description: "The profile it was issued under",
  })
  profileId?: string;

  @ApiProperty({ type: String, required: true, description: "Its serial, hex" })
  serial: string;

  @ApiProperty({
    type: String,
    required: true,
    description: "Its subject, RFC 4514",
  })
  subject: string;

  @ApiProperty({
    type: () => CertificateNames,
    required: true,
    description: "Its alternative names",
  })
  names: CertificateNames;

  @ApiTimestamp({
    required: true,
    description: "An ISO-8601 formatted string: when it becomes valid",
  })
  notBefore: Moment;

  @ApiTimestamp({
    required: true,
    description: "An ISO-8601 formatted string: when it expires",
  })
  notAfter: Moment;

  @ApiProperty({
    ...CERTIFICATE_STATE_ENUM,
    required: true,
    description: "Whether it is valid, revoked or expired",
  })
  state: CertificateStateName;

  @ApiProperty({
    type: () => Revocation,
    required: false,
    description: "Its revocation, if it was revoked",
  })
  revocation?: Revocation;

  @ApiProperty({
    enum: [...KEY_LOCATION_VALUES],
    enumName: "KeyLocation",
    required: true,
    description:
      "Where its private key is: escrowed in the signer, or with the subscriber only",
  })
  keyLocation: KeyLocationName;

  @ApiProperty({
    enum: [...ENROLLMENT_MODE_VALUES],
    enumName: "EnrollmentMode",
    required: false,
    description:
      "How its key came to be certified: a CSR, generated by the signer, or imported from another CA product (XCA)",
  })
  enrollmentMode?: EnrollmentModeName;

  @ApiProperty({
    type: Boolean,
    required: true,
    description: "Whether the CSR its key was certified from is kept",
  })
  hasCsr: boolean;

  @ApiProperty({
    type: String,
    required: true,
    description: "Its key type, e.g. P-256",
  })
  keyAlgorithm: string;

  @ApiTimestamp({
    required: true,
    description:
      "An ISO-8601 formatted string: when its key was first certified; renewal rekeys past the profile's maximum key age",
  })
  keyCreatedAt: Moment;

  @ApiProperty({
    type: String,
    required: false,
    description: "The certificate it renewed",
  })
  renewsId?: string;

  @ApiProperty({
    type: String,
    required: false,
    description: "The certificate that renewed it",
  })
  renewedById?: string;
}

/** A certificate with its PEM and its chain. */
export class FullCertificate extends Certificate {
  @ApiProperty({ type: String, required: true, description: "It, PEM" })
  certificate: string;

  @ApiProperty({
    type: String,
    isArray: true,
    required: true,
    description: "The CAs above it, PEM, nearest first, up to the root",
  })
  chain: string[];
}

/** One subject DN attribute's value. */
export class SubjectAttributeValue {
  @ApiProperty({
    type: String,
    required: true,
    description:
      "The attribute: a name (C, ST, L, O, OU, CN, emailAddress, title, …) or a dotted OID",
  })
  @IsString()
  @IsNotEmpty()
  type: string;

  @ApiProperty({ type: String, required: true, description: "Its value" })
  @IsString()
  @IsNotEmpty()
  @MaxLength(256)
  value: string;
}

export class CertificateSubject {
  @ApiProperty({
    type: String,
    required: false,
    description:
      "The common name: an app name, a person-device, a host (required unless the profile says otherwise)",
  })
  @IsOptional()
  @IsString()
  @IsNotEmpty()
  commonName?: string;

  @ApiProperty({
    type: String,
    required: false,
    description:
      "The organizational unit: a service's deployment, a device kind",
  })
  @IsOptional()
  @IsString()
  organizationalUnit?: string;

  @ApiProperty({
    type: String,
    required: false,
    description: "The organization (the configured one by default)",
  })
  @IsOptional()
  @IsString()
  organization?: string;

  @ApiProperty({
    type: () => SubjectAttributeValue,
    isArray: true,
    required: false,
    description:
      "Any other attributes the profile allows (ADR 0034), each value its own; the fields above are shorthand for CN, OU and O",
  })
  @IsOptional()
  @IsArray()
  @ValidateNested({ each: true })
  @Type(() => SubjectAttributeValue)
  attributes?: SubjectAttributeValue[];
}

