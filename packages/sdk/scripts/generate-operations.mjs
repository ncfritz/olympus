// Writes src/generated/<api>/operations.gen.ts: every operation of the
// API document as { api, method, path, operationId, tag }, exported from
// the entry point as `operations`. Clients use it to label their request
// metrics with the operation called (ADR 0017, @ncfritz/olympus-metrics).
// Also exports the client factory, so a caller can hold its own client
// (per service, or per request in Next.js) instead of the shared `client`.
// Runs after openapi-ts (`pnpm generate`).
import { appendFileSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const APIS = ["olympus", "dionysus", "minerva"];
const METHODS = ["get", "put", "post", "delete", "patch", "head", "options"];

export const operationsOf = (api, document) =>
  Object.entries(document.paths ?? {}).flatMap(([path, item]) =>
    METHODS.flatMap((method) => {
      const operation = item[method];
      return operation?.operationId
        ? [
            {
              api,
              method: method.toUpperCase(),
              path,
              operationId: operation.operationId,
              tag: operation.tags?.[0] ?? "unknown",
            },
          ]
        : [];
    }),
  );

export const render = (
  api,
  operations,
) => `// This file is auto-generated by scripts/generate-operations.mjs

/** An operation of the ${api} API: what request metrics label a call with. */
export interface Operation {
  api: string;
  method: string;
  path: string;
  operationId: string;
  tag: string;
}

export const api = ${JSON.stringify(api)};

export const operations: readonly Operation[] = ${JSON.stringify(operations, null, 2)};
`;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const api of APIS) {
    const document = JSON.parse(
      readFileSync(join(root, `../../apps/api/openapi/${api}.json`), "utf8"),
    );
    const dir = join(root, "src/generated", api);
    writeFileSync(
      join(dir, "operations.gen.ts"),
      render(api, operationsOf(api, document)),
    );
    appendFileSync(
      join(dir, "index.ts"),
      'export { api, type Operation, operations } from "./operations.gen";\n' +
        'export { type Client, createClient, createConfig } from "./client";\n',
    );
    console.log(`Wrote src/generated/${api}/operations.gen.ts`);
  }
}
